// Turns the saved Vobiz project artifact (manual research) into data the Vobiz hub page renders.
//   node scripts/extract-vobiz-hub.mjs <artifact.html>
// Writes src/app/vobiz/hub.css and data/vobiz/{sections.json,checklist.json,accounts.json,partner-types.json}.
// Personal data stays out of the repo: the people table is cut from the outreach page and only company-level facts are kept.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const src = readFileSync(process.argv[2], 'utf8');
const out = 'data/vobiz';
mkdirSync(out, { recursive: true });

const decode = (s) => s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;|&apos;/g, "'").replace(/&nbsp;/g, ' ');
const text = (h) => decode(h.replace(/<br\s*\/?>/gi, ' ').replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ').trim();

// ---------- sections ----------
const sections = {};
const meta = {};
for (const m of src.matchAll(/<section class="view([^"]*)" data-view="([^"]+)"[^>]*>([\s\S]*?)\n    <\/section>/g)) {
  let html = m[3];
  if (m[2] === 'checklist') html = html.replace(/<div id="checklist"><\/div>/, '').replace(/<div class="big-meter">[\s\S]*?<\/div>\s*<\/div>\s*(?=<h2>Deadlines)/, '');
  if (m[2] === 'outreach') {
    // the table of named people at partner companies: private, imported into the CRM instead
    html = html.replace(/<h2>Southeast Asia: partner leads<\/h2>[\s\S]*?<p class="small muted">Tier A and B come from[\s\S]*?<\/p>/, '<h2>Southeast Asia: partner leads</h2>\n      <p>The named decision-makers at the partner companies are in the <a href="#customers">Customer prospecting</a> tab, under <strong>Outreach CRM</strong>. They are private to your browser and are not part of this page.</p>');
  }
  html = html.replace(/<script[\s\S]*?<\/script>/gi, '');
  meta[m[2]] = m[1].trim();
  sections[m[2]] = html;
}

// no email addresses or LinkedIn profile links may remain
// (a few GDP figures cite a person's public LinkedIn page as their source; that is a citation, not contact data, so only the prospecting pages are checked for profile links)
const leaks = Object.entries(sections).flatMap(([k, h]) => [...(h.match(/[\w.+-]+@[\w-]+\.[\w.-]+/g) ?? []), ...(['customers', 'outreach'].includes(k) ? (h.match(/linkedin\.com\/in\//g) ?? []) : [])].map((x) => `${k}: ${x}`));
if (leaks.length) throw new Error('personal data left in sections:\n' + leaks.slice(0, 10).join('\n'));

// class names are prefixed so they cannot collide with the app's own styles
const prefixClasses = (h) => h.replace(/class="([^"]*)"/g, (_, c) => `class="${c.split(/\s+/).filter(Boolean).map((x) => 'hb-' + x).join(' ')}"`);
writeFileSync(`${out}/sections.json`, JSON.stringify({ meta, html: Object.fromEntries(Object.entries(sections).map(([k, v]) => [k, prefixClasses(v)])) }));

// ---------- checklist ----------
const ck = src.slice(src.indexOf('const STEP_NAMES'), src.indexOf('const LABEL'));
const ctx = vm.createContext({});
vm.runInContext(ck + ';this.out={STEP_NAMES,ITEMS}', ctx);
writeFileSync(`${out}/checklist.json`, JSON.stringify(ctx.out));

// ---------- css (content components only) ----------
const css = /<style>([\s\S]*?)<\/style>/.exec(src)[1].replace(/\/\*[\s\S]*?\*\//g, '');
const rules = [];
{
  let depth = 0;
  let cur = '';
  for (const ch of css) {
    cur += ch;
    if (ch === '{') depth++;
    if (ch === '}') {
      depth--;
      if (depth === 0) {
        rules.push(cur.trim());
        cur = '';
      }
    }
  }
}
const SKIP = /^(:root|html|body|\*|img|a:focus|\.shell|\.side|\.brand|\.meter|\.bar|\.nav|\.route|\.node|\.dot|\.plain-icon|main|\.view|\.menu-btn|\.scrim|@media|\.big-meter)/;
const keep = [];
for (const r of rules) {
  const sel = r.slice(0, r.indexOf('{')).trim();
  if (SKIP.test(sel)) continue;
  const body = r.slice(r.indexOf('{'));
  const selectors = sel.split(',').map((s) => s.trim()).map((s) => '.hb-content ' + s.replace(/\.([a-zA-Z][\w-]*)/g, '.hb-$1'));
  keep.push(`${selectors.join(', ')} ${body}`);
}
const tokens = (name) => css.split(name)[1].split('}')[0];
const light = /:root \{([\s\S]*?)\n\}/.exec(css)[1].split('\n').filter((l) => l.includes('--')).join('\n');
const dark = /:root:not\(\[data-theme="light"\]\) \{([\s\S]*?)\n  \}/.exec(css)[1].split('\n').filter((l) => l.includes('--')).join('\n');
void tokens;
writeFileSync('src/app/vobiz/hub.css', `/* generated by scripts/extract-vobiz-hub.mjs from the project artifact */\n.hb-content {\n${light}\n  color: var(--ink);\n  font-size: 15px;\n  line-height: 1.55;\n}\n@media (prefers-color-scheme: dark) {\n  .hb-content {\n${dark}\n  }\n}\n${keep.join('\n')}\n`);

// ---------- accounts ----------
const rowsOf = (tableHtml) => [...tableHtml.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/g)].map((r) => [...r[1].matchAll(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/g)].map((c) => ({ t: text(c[1]), cls: /class="status (\w+)"/.exec(c[1])?.[1] ?? '' })));
const cs = sections.customers;
const strength = (c) => ({ done: 'high', doing: 'medium', todo: 'low', no: 'gap' })[c.cls] ?? 'low';
const SECTOR = [
  [/bfsi|bank|fintech|insurance|lending|financ/i, 'BFSI'],
  [/real estate|property/i, 'Real estate'],
  [/automotive|auto\b|car\b/i, 'Automotive'],
  [/logistic|delivery|post/i, 'Logistics'],
  [/health/i, 'Healthcare'],
  [/e-commerce|retail|food|consumer|restaurant/i, 'E-commerce, retail and food'],
  [/telecom/i, 'Telecom'],
  [/government|public/i, 'Government and public sector'],
  [/travel|leisure|hospitality/i, 'Travel and leisure'],
  [/on-demand|ride|home services|mobility/i, 'On-demand and mobility'],
  [/hr\b|human/i, 'HR and services'],
  [/utilit|industrial|charity/i, 'Utilities, industrial and other'],
];
const sectorOf = (industry) => SECTOR.find(([re]) => re.test(industry))?.[1] ?? 'Other industries';
const REGIONS = ['Middle East', 'Europe', 'Southeast Asia'];

const accounts = [];
const gaps = [];
const block = (from, to) => cs.slice(cs.indexOf(from), to ? cs.indexOf(to) : undefined);
const readBucket = (chunk, source) => {
  for (const rg of chunk.split('<div class="rg-block">').slice(1)) {
    const region = text(/<h3>([\s\S]*?)<\/h3>/.exec(rg)[1]);
    if (!REGIONS.includes(region)) continue;
    const rows = rowsOf(/<table>([\s\S]*?)<\/table>/.exec(rg)[1]).slice(1);
    for (const r of rows) {
      const [industry, a, b, signal, st] = r;
      const gap = strength(st) === 'gap';
      if (gap) {
        gaps.push({ region, industry: industry.t, note: `${a.t}. ${b.t}. ${signal.t}`.replace(/\.\./g, '.') });
        continue;
      }
      if (source === 'competitor-client') accounts.push({ region, kind: 'enterprise', sector: sectorOf(industry.t), industry: industry.t, company: b.t, country: '', signal: signal.t, strength: strength(st), strengthLabel: st.t, source, competitor: a.t });
      else accounts.push({ region, kind: 'enterprise', sector: sectorOf(industry.t), industry: industry.t, company: a.t, country: b.t, signal: signal.t, strength: strength(st), strengthLabel: st.t, source });
    }
  }
};
readBucket(block('<h2>Bucket 1', '<h3>Competitors surfaced'), 'competitor-client');
readBucket(block('<h2>Bucket 2', '<h2>Partner targets'), 'prospect');

// partner types per company come from the (private) people table, but only the company-level columns are kept
const ot = /<h2>Southeast Asia: partner leads<\/h2>[\s\S]*?<table>([\s\S]*?)<\/table>/.exec(src.slice(src.indexOf('data-view="outreach"')));
const partnerTypes = {};
if (ot) for (const r of rowsOf(ot[1]).slice(1)) partnerTypes[r[1].t] = { type: r[2].t, tier: r[3].t, country: r[0].t };

const pt = /<h2>Partner targets \(sell-through\): Southeast Asia<\/h2>[\s\S]*?<table>([\s\S]*?)<\/table>/.exec(cs)[1];
const partners = rowsOf(pt).slice(1).map(([country, company, profile, website, relevance, st]) => ({ region: 'Southeast Asia', kind: 'partner', sector: '', industry: '', company: company.t, country: country.t, profile: profile.t, website: /^to confirm$/i.test(website.t) ? '' : website.t, signal: relevance.t, strength: strength(st), strengthLabel: st.t, source: 'partner-target' }));
const norm = (n) => n.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
const same = (a, b) => a === b || a.startsWith(b + ' ') || b.startsWith(a + ' ');
const typeByName = Object.entries(partnerTypes).map(([k, v]) => [norm(k), v]);
const infer = (p) => (/voice ai|talkbot|voice agent|phone-calling|ai calling|voice and chat agents|voicebot|speech/i.test(p) ? 'Voice AI agent builder' : /bpo/i.test(p) ? 'Call centre / BPO' : /call centre|call-centre|contact centre|ccaas|voip|dial/i.test(p) ? 'Call-centre / CCaaS software' : /chat|conversational|messaging|virtual assistant/i.test(p) ? 'Conversational AI adding voice' : /agency|integrator|custom ai|builder for enterprises|platform for bpo/i.test(p) ? 'AI agency / CX integrator' : 'Voice AI agent builder');
for (const a of partners) {
  const hit = typeByName.find(([k]) => same(k, norm(a.company)));
  a.sector = hit?.[1].type ?? infer(a.profile);
  if (hit) a.tier = hit[1].tier;
}
for (const [name, v] of Object.entries(partnerTypes)) {
  if (partners.some((a) => same(norm(a.company), norm(name)))) continue;
  partners.push({ region: 'Southeast Asia', kind: 'partner', sector: /Unverified/.test(v.type) ? 'To classify' : v.type, industry: '', company: name, country: v.country, profile: '', website: '', signal: 'From the Apollo partner list (27 Nov); not yet reviewed', strength: v.tier === 'A' ? 'high' : v.tier === 'B' ? 'medium' : 'low', strengthLabel: 'Tier ' + v.tier, source: 'apollo-list', tier: v.tier });
}
accounts.push(...partners);

writeFileSync(`${out}/accounts.json`, JSON.stringify({ accounts, gaps }, null, 1));
writeFileSync(`${out}/partner-types.json`, JSON.stringify(partnerTypes, null, 1));
console.log({ sections: Object.keys(sections).length, checklist: ctx.out.ITEMS.length, accounts: accounts.length, byKind: Object.groupBy?.(accounts, (a) => a.kind + '/' + a.region) && Object.fromEntries(Object.entries(Object.groupBy(accounts, (a) => a.kind + '/' + a.region)).map(([k, v]) => [k, v.length])), gaps: gaps.length, partnerTypes: Object.keys(partnerTypes).length, cssRules: keep.length });
